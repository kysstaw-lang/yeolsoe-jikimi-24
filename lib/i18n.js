const LANGS = ['ko', 'en'];

/** Replace {{key}} tokens in a template with the strings of one language. */
function translate(tpl, lang) {
  const dict = STR[lang];
  return tpl.replace(/\{\{(\w+)\}\}/g, (m, key) => {
    if (!(key in dict)) throw new Error(`missing i18n key: ${key} (${lang})`);
    return dict[key].replace(/&(?![a-z]+;|#\d+;)/g, '&amp;'); // bare ampersands -> entities
  });
}

function tr(lang, key, vars) {
  let s = STR[lang][key];
  if (s === undefined) throw new Error(`missing i18n key: ${key} (${lang})`);
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`@@${k}@@`).join(v);
  return s;
}

/** URL of a page in the given language. */
function pageUrl(lang, path) {
  if (lang === 'en') return path === '/' ? '/en' : `/en${path}`;
  return path;
}

module.exports = { STR, LANGS, translate, tr, pageUrl };
